#!/usr/bin/env bash
# Moves ANDOR ANALOG's OSP submodule (external/osp) to an exact, reachable OSP commit, on a branch
# of its own, and runs the checks a dependency update needs before anyone reviews it.
# docs/OSP_DEPENDENCY_UPDATES.md explains the process; this script never pushes or merges.
#
#   tools/update-osp-pin.sh <osp-ref> [build-dir]
#
#   <osp-ref>   an OSP branch (origin/claude/...), tag or commit. It is resolved to a commit
#               once; the pin is that commit, never "the branch's tip" (.gitmodules' branch is
#               not followed: `git submodule update --remote` is never used).
#   [build-dir] an existing plugin build directory (default build-plugin); its tests are run
#               when it exists.
set -euo pipefail

ref="${1:?usage: tools/update-osp-pin.sh <osp-ref> [build-dir]}"
build="${2:-build-plugin}"
root="$(git rev-parse --show-toplevel)"
cd "$root"

if [ -n "$(git status --porcelain --ignore-submodules=dirty)" ]; then
    echo "The working tree has changes: commit or stash them first." >&2
    exit 1
fi

git -C external/osp fetch --quiet origin '+refs/heads/*:refs/remotes/origin/*' '+refs/tags/*:refs/tags/*'
old="$(git rev-parse HEAD:external/osp)"
new="$(git -C external/osp rev-parse --verify "$ref^{commit}")"
if [ "$old" = "$new" ]; then
    echo "external/osp is already at $new."
    exit 0
fi

# Reproducible: the commit must be on a branch or tag of the OSP remote.
if [ -z "$(git -C external/osp branch -r --contains "$new" | head -1)" ] && [ -z "$(git -C external/osp tag --contains "$new" | head -1)" ]; then
    echo "$new is on no OSP branch or tag: a pin must be reachable from the remote." >&2
    exit 1
fi

branch="osp-update/$(git -C external/osp rev-parse --short "$new")"
git switch -c "$branch"
git -C external/osp checkout --quiet --detach "$new"
git add external/osp

echo "== OSP $old -> $new ($(git -C external/osp log -1 --format=%s "$new"))"
echo "== Shared code changed (the areas ANALOG builds on):"
git -C external/osp diff --stat "$old" "$new" -- shared src/engine src/model src/io | tail -1
echo "== Commits:"
git -C external/osp log --oneline "$old..$new" | head -60

git commit --quiet -m "OSP pin: $(git -C external/osp rev-parse --short "$new") ($(git -C external/osp log -1 --format=%s "$new" | cut -c1-60))

OSP $old -> $new.
Generated by tools/update-osp-pin.sh; review per docs/OSP_DEPENDENCY_UPDATES.md before merging."

if [ -d "$build" ]; then
    echo "== Building and testing in $build"
    cmake --build "$build"
    ctest --test-dir "$build" --output-on-failure
else
    echo "== No build directory ($build): configure one and run ctest before review."
fi
echo "== Done: branch $branch. Not pushed. Next: the checklist in docs/OSP_DEPENDENCY_UPDATES.md."
